import os
import random
import string
from ransomguard import config
from ransomguard.logger import log


class HoneypotManager:
    """
    Deploys fake 'network shares' that look like valuable backup/data folders.
    Any file touch inside them is treated as a maximum-severity threat.

    Ransomware spreads across accessible folders. Legit users never enter these.
    So a single access = 100% confidence attack.
    """

    def __init__(self, base_folder=None):
        self.base = base_folder or config.HONEYPOT_FOLDER
        self.honeypot_files = set()
        os.makedirs(self.base, exist_ok=True)

    # ---------- Deploy ----------
    def deploy(self):
        """Create all honeypot shares and their bait files."""
        total = 0
        for share_name, files in config.HONEYPOT_SHARES.items():
            share_path = os.path.join(self.base, share_name)
            os.makedirs(share_path, exist_ok=True)

            for filename, size in files:
                file_path = os.path.join(share_path, filename)
                if not os.path.exists(file_path):
                    self._write_fake_file(file_path, filename, size)
                self.honeypot_files.add(os.path.abspath(file_path).lower())
                total += 1

            # Also add a README to make it look legitimate
            readme = os.path.join(share_path, "_README.txt")
            if not os.path.exists(readme):
                with open(readme, "w", encoding="utf-8") as f:
                    f.write(
                        f"=== {share_name} ===\n"
                        f"Confidential — do not modify.\n"
                        f"Managed by IT Security.\n"
                    )

        log.info(f"[Honeypot] Deployed {total} bait files across "
                 f"{len(config.HONEYPOT_SHARES)} fake shares.")
        print(f"[Honeypot] {total} bait files across "
              f"{len(config.HONEYPOT_SHARES)} fake shares")
        return total

    def _write_fake_file(self, path, filename, size):
        """Write a file that looks real but contains harmless random data."""
        ext = os.path.splitext(filename)[1].lower()

        if ext == ".zip":
            # Real ZIP header
            with open(path, "wb") as f:
                f.write(b"PK\x03\x04" + os.urandom(size))
        elif ext in (".docx", ".xlsx"):
            # Office files are ZIPs — use PK header
            with open(path, "wb") as f:
                f.write(b"PK\x03\x04" + os.urandom(size))
        elif ext == ".pdf":
            with open(path, "wb") as f:
                f.write(b"%PDF-1.4\n" + os.urandom(size))
        elif ext in (".sql", ".pem", ".txt"):
            with open(path, "w", encoding="utf-8") as f:
                header = self._fake_header(ext, filename)
                f.write(header)
                # pad with random-looking content
                for _ in range(size // 80):
                    f.write("".join(random.choices(
                        string.ascii_letters + string.digits + " \n",
                        k=80,
                    )))
        else:
            with open(path, "wb") as f:
                f.write(os.urandom(size))

    def _fake_header(self, ext, filename):
        if ext == ".sql":
            return "-- MySQL dump generated by RansomGuard\n-- WARNING: Confidential\n\n"
        if ext == ".pem":
            return "-----BEGIN PRIVATE KEY-----\n"
        return f"# {filename}\n"

    # ---------- Runtime checks ----------
    def is_honeypot(self, path):
        """Return True if the given path lives inside a honeypot share."""
        if not path:
            return False
        try:
            ap = os.path.abspath(path).lower()
        except Exception:
            return False

        # Direct match
        if ap in self.honeypot_files:
            return True

        # Inside honeypot base folder
        base_low = os.path.abspath(self.base).lower()
        return ap.startswith(base_low + os.sep)

    def is_honeypot_folder(self, folder):
        """Return True if the given folder is the honeypot root or below."""
        if not folder:
            return False
        try:
            ap = os.path.abspath(folder).lower()
        except Exception:
            return False
        base_low = os.path.abspath(self.base).lower()
        return ap == base_low or ap.startswith(base_low + os.sep)

    # ---------- Restore ----------
    def restore(self):
        """Rebuild all bait files after an attack."""
        return self.deploy()

    def folder(self):
        return self.base